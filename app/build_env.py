"""
Builds E:\\ABU\\360Car\\app\\.env from the owner's existing key store (E:\\ABU\\API_KEYS).
Secrets go disk -> disk only; this script never prints a secret value.
Run:  E:\\Miniconda3\\envs\\lotvue\\python.exe build_env.py
"""
import os
import re
from pathlib import Path

KEYS = Path(r".\API_KEYS")
ENV_OUT = Path(__file__).parent / ".env"


def read_key(name: str) -> str:
    f = KEYS / name
    if not f.exists():
        return ""
    txt = f.read_text(encoding="utf-8", errors="replace").strip()
    # take first token that looks like a credential (skip comment lines)
    for line in txt.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            return line.split()[0] if " " in line and len(line.split()[0]) > 8 else line
    return ""


sk = read_key("stripe_sk.txt")
pk = read_key("stripe_pk.txt")
gmail_user = read_key("gmail_user.txt")


def read_app_password(name: str) -> str:
    """Google app passwords are shown as 'xxxx xxxx xxxx xxxx' — strip ALL
    whitespace instead of splitting (read_key would truncate at first space)."""
    f = KEYS / name
    if not f.exists():
        return ""
    for line in f.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            return "".join(line.split())
    return ""


gmail_pw = read_app_password("gmail_app_pw.txt")

# webhook secret: PRESERVE the one already captured in .env (Stripe never
# re-reveals it), else look for a whsec_ token in the key store
whsec = ""
if ENV_OUT.exists():
    m = re.search(r"^STRIPE_WEBHOOK_SECRET=(whsec_\S+)$", ENV_OUT.read_text(encoding="utf-8"), re.M)
    if m:
        whsec = m.group(1)
if not whsec:
    for fn in ["stripe.txt", "stripe_webhook_id.txt", "stripe_webhook_url.txt"]:
        f = KEYS / fn
        if f.exists():
            m = re.search(r"whsec_[A-Za-z0-9]+", f.read_text(errors="replace"))
            if m:
                whsec = m.group(0)
                break

lines = [
    "# LotVue360 production env — generated by build_env.py (secrets from E:\\ABU\\API_KEYS)",
    "LOTVUE_FEATURE_AUTH=1",
    "LOTVUE_FEATURE_PAYMENTS=1",
    "LOTVUE_FEATURE_WATERMARK=1",
    "LOTVUE_PUBLIC_URL=https://lotvue.abuz8ai.com",
    f"STRIPE_SECRET_KEY={sk}",
    f"STRIPE_PUBLISHABLE_KEY={pk}",
    f"STRIPE_WEBHOOK_SECRET={whsec}",
    "LOTVUE_SMTP_HOST=smtp.gmail.com" if gmail_user and gmail_pw else "# LOTVUE_SMTP_HOST=  (gmail creds not found)",
    "LOTVUE_SMTP_PORT=587",
    f"LOTVUE_SMTP_USER={gmail_user}",
    f"LOTVUE_SMTP_PASS={gmail_pw}",
    f"LOTVUE_SMTP_FROM={gmail_user}",
    f"LOTVUE_NOTIFY_EMAIL={gmail_user}",
    "COMFYUI_URL=http://127.0.0.1:8188",
]
ENV_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

# report booleans only — never values
print("env written:", ENV_OUT)
print("stripe_sk present:", bool(sk), "| live-mode:", sk.startswith("sk_live"))
print("stripe_pk present:", bool(pk), "| live-mode:", pk.startswith("pk_live"))
print("webhook_secret present:", bool(whsec))
print("smtp creds present:", bool(gmail_user and gmail_pw), "| user-domain:", gmail_user.split("@")[-1] if gmail_user else "n/a")
